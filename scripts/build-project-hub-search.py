"""Rebuild project-hub/search-index.js from the guide pages.

Run after editing any page in project-hub/:  python3 scripts/build-project-hub-search.py
Each <section class="ph-section" id="..."> becomes one searchable entry.
"""
import html
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "project-hub")

# Must match the PAGES list in project-hub/guide.js.
PAGES = [
    ("index.html", "Start here"),
    ("getting-started.html", "Access & finding your way"),
    ("new-project.html", "Create a project"),
    ("sharing.html", "Sharing, Teams & documents"),
    ("tasks.html", "Tasks & milestones"),
    ("risks-issues.html", "Risks & issues"),
    ("status-reporting.html", "Status & reporting"),
    ("lifecycle-closure.html", "Lifecycle & closing"),
    ("quick-reference.html", "Quick reference"),
]


def text_of(fragment):
    fragment = re.sub(r"<(script|style)\b.*?</\1>", " ", fragment, flags=re.S)
    fragment = re.sub(r'<span class="pin"[^>]*>.*?</span>', " ", fragment, flags=re.S)
    fragment = re.sub(r"<[^>]+>", " ", fragment)
    return re.sub(r"\s+", " ", html.unescape(fragment)).strip()


entries = []
for fname, page_title in PAGES:
    doc = open(os.path.join(ROOT, fname), encoding="utf-8").read()
    hero = re.search(r'<header class="ph-hero">(.*?)</header>', doc, re.S)
    if hero:
        h1 = re.search(r"<h1>(.*?)</h1>", hero.group(1), re.S)
        entries.append({
            "page": fname, "pageTitle": page_title, "id": "main",
            "title": text_of(h1.group(1)) if h1 else page_title,
            "text": text_of(re.sub(r"<h1>.*?</h1>", " ", hero.group(1), flags=re.S)),
        })
    for m in re.finditer(r'<section class="ph-section" id="([^"]+)">(.*?)</section>', doc, re.S):
        body = m.group(2)
        h2 = re.search(r"<h2[^>]*>(.*?)</h2>", body, re.S)
        entries.append({
            "page": fname, "pageTitle": page_title, "id": m.group(1),
            "title": text_of(h2.group(1)) if h2 else m.group(1),
            "text": text_of(re.sub(r"<h2[^>]*>.*?</h2>", " ", body, count=1, flags=re.S)),
        })

with open(os.path.join(ROOT, "search-index.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by scripts/build-project-hub-search.py — do not edit by hand. */\n")
    f.write("window.PH_INDEX = " + json.dumps(entries, ensure_ascii=False, indent=0) + ";\n")
print(f"{len(entries)} entries written to project-hub/search-index.js")
